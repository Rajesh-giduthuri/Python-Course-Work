# #Data types
# Numeric types: int, float, complex
# sequence types: list, tuple, set, range
# string types: str
# mapping types: dict(key-value pair) d.keys() d.values() d.items()
# boolean type: bool(true or false)

num=26
print(type(num)) #int

float_num=26.5
print(type(float_num)) #float   

complex_num=2+3j
print(type(complex_num)) #complex

l=[1,2,3,4,5]
print(type(l)) #list

t=(1,2,3,4,5)
print(type(t)) #tuple

s={1,2,3,4,5}
print(type(s)) #set 

st="Sreekanth"
print(type(st)) #str   

d={"name":"Sreekanth","age":22}
print(type(d)) #dict    

b=True
print(type(b)) #bool
