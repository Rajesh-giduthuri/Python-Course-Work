def modulo_division(a,b):
    if b==0:
        return "Division by zero is not allowed."
    return a%b

def floor_division(a,b):
    if b==0:
        return "Division by zero is not allowed."
    return a//b

def normal_division(a,b):
    if b==0:
        return "Division by zero is not allowed."
    return a/b
